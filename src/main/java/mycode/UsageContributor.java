package mycode;

/**
 * 声明「我在主循环之外还会另花 token」的工具实现的接口。
 *
 * 典型是 task（子代理）工具：子代理自己跑多轮模型调用，这些消耗发生在
 * Agent 主循环的视野之外 —— 主循环只看见一条结果文本，看不见钱花哪去了。
 *
 * 约定：实现方把主循环外产生的用量攒在内部；Agent 每次工具执行完后调
 * drainUsage() 取走并清零，并入本次 run 的总账。这样 ChatSession、/cost
 * 那条统计链路一行都不用改，子代理的开销就能如实计入会话成本。
 *
 * 当前工具调用是顺序执行的，攒取不需要加锁；将来若做并行派发，
 * 实现方要换成线程安全的累积（这是并行化的已知前置项）。
 * @author my
 */
public interface UsageContributor {

    /** 取走并清零攒下的用量（drain 语义：取完归零，不会重复计入） */
    Usage drainUsage();
}
